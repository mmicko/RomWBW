; **********************************************************************
; **  Terminal emulation
; **********************************************************************
SCROLL .EQU	$D0			; scroll register
;
; Prints one character
;
PRINT_CHAR:
	LD	B,10				;char is 10 pixels
	MLT BC				;char * 10 (pixela)
	LD	HL,CHARSET
	ADD	HL,BC				;BC is offset from start of font data
	EX	DE,HL
	CALL	GET_ADDRESS			;get RAM location in BC
	LD	L,10
	JR	C,PRINT_FROM_HALF		;if carry is set, char starts from half byte in screen RAM
PRINT_FROM_FULL:
	PUSH	HL
	LD	A,(DE)				;DE is character address in charset
	RLCA
	RLCA
	RLCA
	RLCA
	AND	0FH
	LD	HL,PIXEL_TABLE
	ADD	A,L
	LD	L,A
	LD	A,(HL)
	OUT	(C),A
	INC	B
	LD	A,(DE)
	AND	0FH
	LD	HL,PIXEL_TABLE
	ADD	A,L
	LD	L,A
	LD	A,(HL)
	AND	0FH
	LD	L,A
	IN	A,(C)
	AND	0F0H
	OR	L
	OUT	(C),A
	DEC	B
	INC	C
	INC	DE
	POP	HL
	DEC	L
	JR	NZ,PRINT_FROM_FULL
	JR	PRINT_DONE
PRINT_FROM_HALF:
	PUSH	HL
	LD	A,(DE)
	RLCA
	RLCA
	AND	3
	LD	HL,PIXEL_TABLE
	ADD	A,L
	LD	L,A
	LD	A,(HL)
	AND	0F0H
	LD	L,A
	IN	A,(C)
	AND	0FH
	OR	L
	OUT	(C),A
	INC	B
	LD	A,(DE)
	RRCA
	RRCA
	AND	0FH
	LD	HL,PIXEL_TABLE
	ADD	A,L
	LD	L,A
	LD	A,(HL)
	OUT	(C),A
	DEC	B
	INC	C
	INC	DE
	POP	HL
	DEC	L
	JR	NZ,PRINT_FROM_HALF
PRINT_DONE:
	LD	A,(COLUMN_POSITION)
	INC	A
	CP	80				;end of row?
	JR	NZ,NEXT_COL			;no
	XOR	A				;yes, new column is zero
NEXT_COL:
	LD	(COLUMN_POSITION),A		;save new column position
	RET					;and finish

GET_ADDRESS:
	LD	A,(ROW_POSITION)
	LD	B,A
	LD	C,10
	MLT BC				;row x10
	LD	A,(SCROLL_LOCATION)
	ADD	A,C
	LD	C,A
	LD	A,(COLUMN_POSITION)
	LD	B,A
	ADD	A,A
	ADD	A,B				;col x3
	ADD	A,2				;+2
	SRL	A				;div /2
	LD	B,A
	SET	7,B				;plus high bit
	RET					;if carry set, it is odd char in row
	
SCROLL_ONE_LINE:
	LD	A,(SCROLL_LOCATION)
	ADD	A,10
	LD	(SCROLL_LOCATION),A
	OUT0	(SCROLL),A
	ADD	A,0E6H
	LD	C,A
	LD	B,080H
	LD	E,0DH

CLEAR_LINES_IN_E:
	XOR	A
CLRL1:	
	LD	D,E
	PUSH	BC
CLRL2:	
	OUT	(C),A
	INC	C
	OUT	(C),A
	INC	C
	DEC	D
	JR	NZ,CLRL2
	POP	BC
	INC	B
	JR	NZ,CLRL1
	RET
	
