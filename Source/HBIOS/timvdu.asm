ORG_TIMVDU	.EQU	$
;
	.DW	SIZ_TIMVDU		; MODULE SIZE
	.DW	TIMVDU_INITPHASE		; ADR OF INIT PHASE HANDLER
;
TIMVDU_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	JP	Z,TIMVDU_PREINIT		; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,TIMVDU_INIT		; DO INIT
	RET				; DONE
;
; HARDWARE RESET PRIOR TO ROMWBW CONSOLE INITIALIZATION
;
TIMVDU_PREINIT:
;
	LD	IY,TIMVDU_IDAT		; POINTER TO INSTANCE DATA
	CALL TIMVDU_VDAINI

	XOR	A			; SIGNAL SUCCESS
	RET				; DONE
;
; POST CONSOLE INITIALIZATION
;
TIMVDU_INIT:
	LD	IY,TIMVDU_IDAT		; POINTER TO INSTANCE DATA
	CALL	NEWLINE			; FORMATTING
	PRTS("TIMVDU: IO=$")
	LD	HL,TIMVDU_BASE
	CALL	PRTHEXWORDHL

	; ADD OURSELVES TO VDA DISPATCH TABLE
	LD	BC,TIMVDU_FNTBL		; BC := FUNCTION TABLE ADDRESS
	LD	DE,TIMVDU_IDAT		; DE := TIMVDU INSTANCE DATA PTR
	CALL	VDA_ADDENT		; ADD ENTRY, A := UNIT ASSIGNED

	; INITIALIZE EMULATION
	LD	C,A			; C := ASSIGNED VIDEO DEVICE NUM
	LD	DE,TIMVDU_FNTBL		; DE := FUNCTION TABLE ADDRESS
	LD	HL,TIMVDU_IDAT		; HL := TIMVDU INSTANCE DATA PTR
	CALL	TERM_ATTACH		; DO IT

	XOR	A			; SIGNAL SUCCESS
	RET				; DONE


