	LD	C,0		; C := ATTRIBUTES (UNDEFINED)
	LD	D,VDADEV_TIM	; D := DEVICE TYPE
	LD	E,0		; E := PHYSICAL UNIT IS ALWAYS ZERO
	LD	H,0		; H := 0, DRIVER HAS NO MODES
	LD	L,$80		; L := BASE I/O ADDRESS
	XOR	A		; SIGNAL SUCCESS
	RET

