TIMVDU_VDAINI:
; Fill screen memory
    LD      BC,TIMVDU_BASE
Loop:
	XOR     A
	OUT     (C),A
	INC     BC
	BIT     7,B
	JR      NZ,Loop 

	XOR	A			; SIGNAL SUCCESS
	RET

TIMVDU_VDAQRY:
	LD	C,$00		; MODE ZERO IS ALL WE KNOW
	LD	A,24
	LD	D,A
	LD	A,80
	LD	E,A
	LD	HL,$0		; EXTRACTION OF CURRENT BITMAP DATA NOT SUPPORTED YET
	XOR	A		; SIGNAL SUCCESS
	RET

TIMVDU_VDARES:
	XOR	A		; SIGNAL SUCCESS
	RET

